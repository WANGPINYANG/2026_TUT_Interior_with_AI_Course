/* 整數邊界測試。跑法：node scripts/整數邊界.test.js

   補的是 2026-10-03 交叉稽核照出來的盲區：
   我原有的測試全部在打極端值——壞值掃描用 0／負數／空白／非數字／極大值，
   暴力測試用 1e308 與隨機模糊。**沒有一套測正常值。**

   結果是這個 bug 活了下來：10×10 公尺房間、100×100 公分磚、損耗 10%，
   每一個都是現場天天遇到的數字，但 100 × 1.1 在浮點下是 110.00000000000001，
   Math.ceil 得到 111，使用者多買一箱。
   而且中間值顯示時被四捨五入成 110，畫面上完全看不出哪裡錯。

   這支測的是「數學上剛好落在整數的輸入，進位後不可以被多加一」。 */
'use strict';

var 引擎 = require('./公式.js');
var 計算 = 引擎.計算;

var 失敗 = 0;
function 驗(名稱, 實得, 預期) {
  var 過 = 實得 === 預期;
  if (!過) { 失敗++; }
  console.log('  ' + (過 ? '通過' : '失敗') + '｜' + 名稱 +
              '　實得 ' + 實得 + (過 ? '' : '，應為 ' + 預期));
}

/* ── A 手算案例：結果剛好是整數 ── */
console.log('── A 剛好落在整數的正常輸入 ──');

/* 磁磚：100 m² ÷ 1 m² = 100 片，× 1.1 = 110 片整，每箱 10 片 = 11 箱整 */
var 磚1 = 計算('磁磚', { 長: 10, 寬: 10, 扣除: 0, 磚長: 100, 磚寬: 100,
                        填縫: 0, 損耗: 10, 每箱片數: 10 }).值;
驗('磁磚 100片×1.1 = 110 片', 磚1.片數, 110);
驗('磁磚 110片÷10 = 11 箱', 磚1.箱數, 11);

var 磚2 = 計算('磁磚', { 長: 10, 寬: 10, 扣除: 0, 磚長: 100, 磚寬: 100,
                        填縫: 0, 損耗: 25, 每箱片數: 25 }).值;
驗('磁磚 100片×1.25 = 125 片', 磚2.片數, 125);
驗('磁磚 125片÷25 = 5 箱', 磚2.箱數, 5);

var 磚3 = 計算('磁磚', { 長: 10, 寬: 10, 扣除: 0, 磚長: 100, 磚寬: 100,
                        填縫: 0, 損耗: 0, 每箱片數: 4 }).值;
驗('磁磚 無損耗 100 片', 磚3.片數, 100);
驗('磁磚 100片÷4 = 25 箱', 磚3.箱數, 25);

/* 油漆：牆面積 75.7 m²、1 道、塗佈率 1、無損耗 → 75.7 L ÷ 3.785 = 20 加侖整 */
var 漆1 = 計算('油漆', { ping: 10, wallH: 4, perim: 20, openArea: 4.3,
                        rate: 1, coats: 1, loss: 0 }).值;
驗('油漆 75.7 L ÷ 3.785 = 20 加侖', 漆1.加侖數, 20);

/* 窗簾：布寬需求 640 ÷ 幅寬 160 = 4 幅整 */
var 簾1 = 計算('窗簾', { 窗寬: 300, 窗高: 100, 倍數: 2, 幅寬: 160,
                        兩側收邊: 40, 上下摺邊: 25 }).值;
驗('窗簾 640 ÷ 160 = 4 幅', 簾1.幅數, 4);

/* ── B 掃描：真值落在整數時，進位不可以多加一 ── */
console.log('');
console.log('── B 掃描：凡是真值為整數的組合，進位結果必須等於它 ──');

function 真值進位(v) {
  /* 用高精度比對：把雜訊抹掉之後才是數學上的真值 */
  var 乾淨 = Math.round(v * 1e9) / 1e9;
  return Math.ceil(乾淨);
}

var 掃描失敗 = [];
var 掃描數 = 0;

/* 磁磚：各種面積 × 損耗率 × 每箱片數 */
[1, 4, 9, 16, 25, 100].forEach(function (面積) {
  [0, 5, 10, 20, 25, 50, 100].forEach(function (損耗) {
    [1, 2, 4, 5, 10, 11, 25].forEach(function (每箱) {
      掃描數++;
      var i = { 長: 面積, 寬: 1, 扣除: 0, 磚長: 100, 磚寬: 100,
                填縫: 0, 損耗: 損耗, 每箱片數: 每箱 };
      var r = 計算('磁磚', i).值;
      var 片真值 = 真值進位(面積 * 1 / 1 * (1 + 損耗 / 100));
      var 箱真值 = 真值進位(片真值 / 每箱);
      if (r.片數 !== 片真值 || r.箱數 !== 箱真值) {
        掃描失敗.push('磁磚 面積' + 面積 + ' 損耗' + 損耗 + '% 每箱' + 每箱 +
                      ' → 片 ' + r.片數 + '(應 ' + 片真值 + ')　箱 ' +
                      r.箱數 + '(應 ' + 箱真值 + ')');
      }
    });
  });
});

/* 窗簾：各種窗寬 × 倍數 × 幅寬 */
[100, 150, 200, 300, 400].forEach(function (窗寬) {
  [1.5, 2, 2.5, 3].forEach(function (倍數) {
    [140, 150, 160, 280, 300].forEach(function (幅寬) {
      掃描數++;
      var i = { 窗寬: 窗寬, 窗高: 200, 倍數: 倍數, 幅寬: 幅寬,
                兩側收邊: 10, 上下摺邊: 25 };
      var r = 計算('窗簾', i).值;
      var 幅真值 = 真值進位((窗寬 * 倍數 + 10) / 幅寬);
      if (r.幅數 !== 幅真值) {
        掃描失敗.push('窗簾 窗寬' + 窗寬 + ' 倍數' + 倍數 + ' 幅寬' + 幅寬 +
                      ' → 幅數 ' + r.幅數 + '(應 ' + 幅真值 + ')');
      }
    });
  });
});

console.log('  掃了 ' + 掃描數 + ' 組正常參數組合');
if (!掃描失敗.length) {
  console.log('  通過｜沒有任何一組被多進一位');
} else {
  失敗 += 掃描失敗.length;
  console.log('  失敗｜' + 掃描失敗.length + ' 組被多進一位：');
  掃描失敗.slice(0, 10).forEach(function (s) { console.log('        ' + s); });
}

console.log('');
console.log(失敗 ? '共 ' + 失敗 + ' 項失敗' : '全部通過');
process.exit(失敗 ? 1 : 0);
